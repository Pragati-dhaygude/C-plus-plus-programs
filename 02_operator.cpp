    cout<<"a==b :"<<(a==b)<<endl;
    cout<<"a!=b:"<<(a!=b)<<endl;
    cout<<"a>b:"<<(a>b)<<endl;
    cout<<"a<b:"<<(a<b)<<endl;
    cout<<"a>=b:"<<(a>=b)<<endl;
    cout<<"a<=b:"<<(a<=b)<<endl;

